def _require_jpype() -> None:
    if jpype is None:
        raise RuntimeError(
            "JPype is required for JForex downloader. Install with: pip install jpype1"
        )


def _java_exception_types() -> tuple[type[BaseException], ...]:
    if jpype is None:
        return ()
    java_exception = getattr(jpype, "JException", None)
    if isinstance(java_exception, type):
        return (java_exception,)
    return ()


def _raise_jforex_runtime_error(context: str, exc: BaseException) -> None:
    logger.exception("%s: %s", context, exc)
    raise RuntimeError(f"{context}: {exc}") from exc


def _normalize_timeframe(timeframe: str) -> str:
    normalized = TIMEFRAME_ALIASES.get(timeframe.strip().lower())
    if not normalized:
        raise ValueError(
            f"Unsupported timeframe: {timeframe}. Use one of: {sorted(TIMEFRAME_ALIASES)}"
        )
    return normalized


def _parse_datetime(value: str | datetime, *, is_end: bool) -> datetime:
    if isinstance(value, datetime):
        ts = pd.Timestamp(value)
    else:
        text = value.strip()
        ts = pd.to_datetime(text, utc=True, errors="raise")
        if DATE_ONLY_RE.fullmatch(text):
            if is_end:
                ts = ts + pd.Timedelta(days=1) - pd.Timedelta(milliseconds=1)

    if ts.tzinfo is None:
        ts = ts.tz_localize("UTC")
    else:
        ts = ts.tz_convert("UTC")
    return ts.to_pydatetime()


def _read_auth_config() -> DukascopyAuthConfig:
    username = (os.getenv("DUKASCOPY_USERNAME") or os.getenv("DUKASCOPY_LOGIN") or "").strip()
    password = (os.getenv("DUKASCOPY_PASSWORD") or "").strip()
    jnlp_url = _resolve_jnlp_url()

    if not username or not password:
        raise RuntimeError(
            "Missing Dukascopy credentials. Set DUKASCOPY_USERNAME and DUKASCOPY_PASSWORD."
        )
    if not jnlp_url:
        raise RuntimeError("DUKASCOPY_JNLP_URL is empty.")

    return DukascopyAuthConfig(username=username, password=password, jnlp_url=jnlp_url)


def _resolve_jnlp_url() -> str:
    jnlp_url = (os.getenv("DUKASCOPY_JNLP_URL") or DEFAULT_JNLP_URL).strip()
    if not jnlp_url:
        raise RuntimeError("DUKASCOPY_JNLP_URL is empty.")
    return jnlp_url


def _discover_jars(root: Path) -> list[Path]:
    if not root.exists():
        return []

    search_roots = [root]
    if (root / "lib").exists():
        search_roots.append(root / "lib")
    if (root / "libs").exists():
        search_roots.append(root / "libs")

    jars: list[Path] = []
    for search_root in search_roots:
        jars.extend(sorted(path for path in search_root.rglob("*.jar") if path.is_file()))

    deduped: list[Path] = []
    seen: set[Path] = set()
    for jar in jars:
        if jar in seen:
            continue
        deduped.append(jar)
        seen.add(jar)
    return deduped


def _parse_jnlp_jar_urls(jnlp_url: str, *, _visited: set[str] | None = None) -> list[str]:
    visited = _visited if _visited is not None else set()
    if jnlp_url in visited:
        return []
    visited.add(jnlp_url)

    try:
        with urlopen(jnlp_url, timeout=20) as response:
            payload = response.read()
    except URLError as exc:
        raise RuntimeError(f"Failed to fetch JNLP '{jnlp_url}': {exc}") from exc

    try:
        root = ET.fromstring(payload)
    except ET.ParseError as exc:
        raise RuntimeError(f"Invalid JNLP payload from '{jnlp_url}': {exc}") from exc

    codebase = (root.attrib.get("codebase") or "").strip()
    base_url = codebase or jnlp_url
    jar_urls: list[str] = []

    for element in root.iter():
        tag = element.tag.rsplit("}", 1)[-1].lower()
        href = (element.attrib.get("href") or "").strip()
        if not href:
            continue
        if tag in {"jar", "nativelib"}:
            jar_urls.append(urljoin(base_url, href))
        elif tag == "extension":
            extension_url = urljoin(base_url, href)
            jar_urls.extend(_parse_jnlp_jar_urls(extension_url, _visited=visited))

    deduped: list[str] = []
    seen: set[str] = set()
    for entry in jar_urls:
        if entry in seen:
            continue
        deduped.append(entry)
        seen.add(entry)
    return deduped


def _download_jforex_jars_from_jnlp(jnlp_url: str, target_dir: Path) -> list[Path]:
    jar_urls = _parse_jnlp_jar_urls(jnlp_url)
    if not jar_urls:
        raise RuntimeError(f"No jar resources found in JNLP '{jnlp_url}'.")

    target_dir.mkdir(parents=True, exist_ok=True)
    downloaded: list[Path] = []

    for jar_url in jar_urls:
        file_name = Path(urlparse(jar_url).path).name
        if not file_name.endswith(".jar"):
            continue
        output_path = target_dir / file_name
        if not output_path.exists() or output_path.stat().st_size == 0:
            try:
                with urlopen(jar_url, timeout=30) as response:
                    output_path.write_bytes(response.read())
            except URLError as exc:
                raise RuntimeError(f"Failed to download JAR '{jar_url}': {exc}") from exc
        downloaded.append(output_path)

    if not downloaded:
        raise RuntimeError(f"JNLP '{jnlp_url}' did not resolve any downloadable JAR files.")

    deduped: list[Path] = []
    seen: set[Path] = set()
    for path in downloaded:
        if path in seen:
            continue
        deduped.append(path)
        seen.add(path)
    return deduped


def _resolve_jforex_classpath() -> list[str]:
    explicit = os.getenv("JFOREX_CLASSPATH") or os.getenv("JFOREX_JARS")
    if explicit:
        return [entry.strip() for entry in explicit.split(os.pathsep) if entry.strip()]

    repo_root = Path(__file__).resolve().parents[2]
    home_env = os.getenv("JFOREX_HOME")
    candidates: list[Path] = []
    if home_env:
        candidates.append(Path(home_env).expanduser())
    candidates.extend(
        [
            DATA_DIR / ".jforex-sdk",
            repo_root / "download" / "jforex",
            repo_root / "download" / "jforex-sdk",
            repo_root / "download",
        ]
    )

    classpath: list[str] = []
    for root in candidates:
        classpath.extend(str(path) for path in _discover_jars(root))

    if classpath:
        return classpath

    bootstrap_dir = DATA_DIR / ".jforex-sdk"
    try:
        jnlp_url = _resolve_jnlp_url()
        downloaded = _download_jforex_jars_from_jnlp(jnlp_url, bootstrap_dir)
        logger.info("Bootstrapped %d JForex SDK jars from %s", len(downloaded), jnlp_url)
        return [str(path) for path in downloaded]
    except Exception as exc:  # noqa: BLE001
        logger.warning("Unable to bootstrap JForex SDK jars: %s", exc)
        return []


def _ensure_jvm_started() -> None:
    _require_jpype()

    with JVM_START_LOCK:
        if jpype.isJVMStarted():
            return

        classpath = _resolve_jforex_classpath()
        if not classpath:
            raise RuntimeError(
                "Could not resolve JForex SDK classpath. "
                "Set JFOREX_CLASSPATH (or JFOREX_JARS) to your SDK jars."
            )

        try:
            jpype.startJVM(classpath=classpath, convertStrings=False)
        except _java_exception_types() as exc:
            _raise_jforex_runtime_error("Failed to start JVM for JForex SDK", exc)
        except Exception as exc:  # noqa: BLE001
            raise RuntimeError(
                f"Failed to start JVM for JForex SDK. Classpath={classpath}. Error: {exc}"
            ) from exc


def prewarm_jvm() -> None:
    """Start JVM and validate core JForex SDK imports once at app startup."""
    _ensure_jvm_started()
    try:
        from com.dukascopy.api import Instrument  # type: ignore
    except Exception as exc:  # noqa: BLE001
        raise RuntimeError(f"JForex SDK import failed for prewarm: {exc}") from exc
    if Instrument is None:
        raise RuntimeError("JForex SDK prewarm failed: Instrument class is unavailable")


def _resolve_java_instrument(symbol: str) -> tuple[str, str, Any]:
    _ensure_jvm_started()

    try:
        from com.dukascopy.api import Instrument
    except _java_exception_types() as exc:
        _raise_jforex_runtime_error("JForex SDK import failed for com.dukascopy.api.Instrument", exc)
    except Exception as exc:  # noqa: BLE001
        _raise_jforex_runtime_error("JForex SDK import failed for com.dukascopy.api.Instrument", exc)

    normalized_symbol, instrument_key, asset_class = _resolve_symbol_and_instrument(symbol)
    candidates = [
        instrument_key.upper(),
        normalized_symbol.upper(),
    ]
    if len(normalized_symbol) == 6 and normalized_symbol.isalpha():
        candidates.insert(0, f"{normalized_symbol[:3]}/{normalized_symbol[3:]}")

    for candidate in dict.fromkeys(candidates):
        try:
            java_instrument = Instrument.fromString(candidate)
            if java_instrument is not None:
                return normalized_symbol, asset_class, java_instrument
        except _java_exception_types():
            logger.debug(
                "Instrument.fromString failed for candidate %s",
                candidate,
                exc_info=True,
            )
        except Exception:  # noqa: BLE001
            logger.debug(
                "Instrument.fromString failed for candidate %s",
                candidate,
                exc_info=True,
            )

        try:
            java_instrument = getattr(Instrument, candidate.replace("/", ""))
            if java_instrument is not None:
                return normalized_symbol, asset_class, java_instrument
        except _java_exception_types():
            logger.debug(
                "Instrument attribute lookup failed for candidate %s",
                candidate,
                exc_info=True,
            )
        except AttributeError:
            continue
        except Exception:  # noqa: BLE001
            logger.debug(
                "Instrument attribute lookup failed for candidate %s",
                candidate,
                exc_info=True,
            )
            continue

    raise ValueError(f"Could not resolve JForex Instrument for symbol '{symbol}'.")


def _window_ms(base_timeframe: str) -> int:
    days = WINDOW_DAYS_BY_BASE_TF[base_timeframe]
    return int(days * 24 * 60 * 60 * 1000)


def _query_jforex_history(
    *,
    java_instrument: Any,
    base_timeframe: str,
    start_ms: int,
    end_ms: int,
    auth: DukascopyAuthConfig,
    offer_side_name: str,
    timeout_seconds: int,
    cache_dir: Path,
) -> pd.DataFrame:
    _ensure_jvm_started()

    try:
        from com.dukascopy.api import OfferSide, Period
        from com.dukascopy.api.system import ClientFactory
        from java.io import File
        from java.util import HashSet
    except _java_exception_types() as exc:
        _raise_jforex_runtime_error("Failed to import JForex SDK runtime classes", exc)
    except Exception as exc:  # noqa: BLE001
        _raise_jforex_runtime_error("Failed to import JForex SDK runtime classes", exc)

    state = QueryState()

    @jpype.JImplements("com.dukascopy.api.system.ISystemListener")
    class _SystemListener:
        @jpype.JOverride
        def onStart(self, processId):  # noqa: N802
            del processId

        @jpype.JOverride
        def onStop(self, processId):  # noqa: N802
            del processId

        @jpype.JOverride
        def onConnect(self):  # noqa: N802
            state.connected.set()

        @jpype.JOverride
        def onDisconnect(self):  # noqa: N802
            pass

    @jpype.JImplements("com.dukascopy.api.IStrategy")
    class _HistoryStrategy:
        @jpype.JOverride
        def onStart(self, context):  # noqa: N802
            try:
                history = context.getHistory()
                data_service = context.getDataService()
                rows: list[tuple[Any, ...]] = []
                step_ms = _window_ms(base_timeframe)

                if base_timeframe == "tick":
                    first_ms = int(data_service.getTimeOfFirstTick(java_instrument))
                    if first_ms >= JAVA_LONG_MAX:
                        state.rows = []
                        return
                    cursor = max(start_ms, first_ms)
                    while cursor <= end_ms:
                        window_end = min(cursor + step_ms - 1, end_ms)
                        ticks = history.getTicks(java_instrument, cursor, window_end)
                        for tick in ticks:
                            rows.append(
                                (
                                    int(tick.getTime()),
                                    float(tick.getAsk()),
                                    float(tick.getBid()),
                                    float(tick.getAskVolume()),
                                    float(tick.getBidVolume()),
                                )
                            )
                        cursor = window_end + 1
                else:
                    period = getattr(Period, JFOREX_PERIOD_ATTR[base_timeframe])
                    offer_side = getattr(OfferSide, offer_side_name)
                    first_ms = int(data_service.getTimeOfFirstCandle(java_instrument, period))
                    if first_ms >= JAVA_LONG_MAX:
                        state.rows = []
                        return
                    cursor = max(start_ms, first_ms)
                    while cursor <= end_ms:
                        window_end = min(cursor + step_ms - 1, end_ms)
                        bars = history.getBars(
                            java_instrument,
                            period,
                            offer_side,
                            cursor,
                            window_end,
                        )
                        for bar in bars:
                            rows.append(
                                (
                                    int(bar.getTime()),
                                    float(bar.getOpen()),
                                    float(bar.getHigh()),
                                    float(bar.getLow()),
                                    float(bar.getClose()),
                                    float(bar.getVolume()),
                                )
                            )
                        cursor = window_end + 1

                state.rows = rows
            except _java_exception_types() as exc:
                logger.exception("JForex history strategy failed with Java exception: %s", exc)
                state.error = RuntimeError(f"JForex history query failed: {exc}")
            except Exception as exc:  # noqa: BLE001
                logger.exception("JForex history strategy failed: %s", exc)
                state.error = RuntimeError(f"JForex history query failed: {exc}")
            finally:
                state.completed.set()
                try:
                    context.stop()
                except _java_exception_types():
                    logger.debug("JForex strategy context.stop() raised Java exception", exc_info=True)
                except Exception:  # noqa: BLE001
                    logger.debug("JForex strategy context.stop() raised exception", exc_info=True)

        @jpype.JOverride
        def onAccount(self, account):  # noqa: N802
            del account

        @jpype.JOverride
        def onMessage(self, message):  # noqa: N802
            del message

        @jpype.JOverride
        def onStop(self):  # noqa: N802
            pass

        @jpype.JOverride
        def onTick(self, instrument, tick):  # noqa: N802
            del instrument, tick

        @jpype.JOverride
        def onBar(self, instrument, period, askBar, bidBar):  # noqa: N802
            del instrument, period, askBar, bidBar

    client = None
    process_id: int | None = None

    try:
        client = ClientFactory.getDefaultInstance()
        client.setSystemListener(_SystemListener())

        cache_dir.mkdir(parents=True, exist_ok=True)
        client.setCacheDirectory(File(str(cache_dir)))

        client.connect(auth.jnlp_url, auth.username, auth.password)

        connect_deadline = time.monotonic() + 30
        while time.monotonic() < connect_deadline:
            if state.connected.is_set() or bool(client.isConnected()):
                break
            time.sleep(0.2)
        else:
            raise TimeoutError("JForex connection timed out.")

        subscribed = HashSet()
        subscribed.add(java_instrument)
        client.setSubscribedInstruments(subscribed)

        strategy = _HistoryStrategy()
        process_id = int(client.startStrategy(strategy))

        if not state.completed.wait(timeout_seconds):
            raise TimeoutError(f"JForex data request timed out after {timeout_seconds}s.")

        if state.error is not None:
            raise state.error
    except _java_exception_types() as exc:
        _raise_jforex_runtime_error("JForex SDK request execution failed", exc)

    finally:
        if client is not None and process_id is not None:
            try:
                client.stopStrategy(process_id)
            except _java_exception_types():
                logger.debug("JForex client.stopStrategy() raised Java exception", exc_info=True)
            except Exception:  # noqa: BLE001
                logger.debug("JForex client.stopStrategy() raised exception", exc_info=True)
        if client is not None:
            try:
                if bool(client.isConnected()):
                    client.disconnect()
            except _java_exception_types():
                logger.debug("JForex client.disconnect() raised Java exception", exc_info=True)
            except Exception:  # noqa: BLE001
                logger.debug("JForex client.disconnect() raised exception", exc_info=True)

    if base_timeframe == "tick":
        df = pd.DataFrame(
            state.rows,
            columns=["timestamp", "ask", "bid", "ask_vol", "bid_vol"],
        )
    else:
        df = pd.DataFrame(
            state.rows,
            columns=["timestamp", "open", "high", "low", "close", "volume"],
        )

    if df.empty:
        return df

    df["timestamp"] = pd.to_datetime(df["timestamp"], unit="ms", utc=True)
    df = df.sort_values("timestamp").drop_duplicates(subset=["timestamp"]).reset_index(drop=True)
    return df


def _normalize_offer_side(value: str | None) -> str:
    normalized = str(value or "bid").strip().lower()
    if normalized not in {"bid", "ask", "both"}:
        raise ValueError("offer_side must be one of: bid, ask, both")
    return normalized


def _normalize_timeframe_for_file_suffix(timeframe: str) -> str:
    return timeframe.replace("1m", "m1").replace("5m", "m5").replace("15m", "m15").replace(
        "30m", "m30"
    ).replace("1h", "h1").replace("4h", "h4").replace("1d", "d1").replace("1w", "w1")


def _bars_with_offer_prefix(df: pd.DataFrame, offer_side: str) -> pd.DataFrame:
    if df.empty:
        return df.copy()
    side = offer_side.lower()
    renamed = df.rename(
        columns={
            "open": f"{side}_open",
            "high": f"{side}_high",
            "low": f"{side}_low",
            "close": f"{side}_close",
            "volume": f"{side}_volume",
        }
    )
    return renamed


def _resample_offer_prefixed(df: pd.DataFrame, target_tf: str, offer_side: str) -> pd.DataFrame:
    base = df.rename(
        columns={
            f"{offer_side}_open": "open",
            f"{offer_side}_high": "high",
            f"{offer_side}_low": "low",
            f"{offer_side}_close": "close",
            f"{offer_side}_volume": "volume",
        }
    )
    resampled = resample_ohlcv(base, target_tf)
    return _bars_with_offer_prefix(resampled, offer_side)


def _build_offer_side_output_path(base_path: Path, target_tf: str, offer_side: str) -> Path:
    stem = base_path.stem
    normalized_tf = _normalize_timeframe_for_file_suffix(target_tf)
    suffix = f"{normalized_tf}_{offer_side}"
    if stem == normalized_tf:
        stem = suffix
    elif stem.endswith(f"_{normalized_tf}"):
        stem = f"{stem}_{offer_side}"
    else:
        stem = suffix
    return base_path.with_name(f"{stem}{base_path.suffix}")


def _query_bars_for_offer_side(
    *,
    java_instrument: Any,
    base_tf: str,
    offer_side: str,
    start_dt: datetime,
    end_dt: datetime,
    auth: DukascopyAuthConfig,
    timeout_seconds: int,
    cache_path: Path,
) -> pd.DataFrame:
    base_df = _query_jforex_history(
        java_instrument=java_instrument,
        base_timeframe=base_tf,
        start_ms=int(start_dt.timestamp() * 1000),
        end_ms=int(end_dt.timestamp() * 1000),
        auth=auth,
        offer_side_name=offer_side.upper(),
        timeout_seconds=timeout_seconds,
        cache_dir=cache_path,
    )
    if base_df.empty:
        return base_df
    return _bars_with_offer_prefix(base_df, offer_side)


class JForexDownloader(Downloader):
    """Dukascopy downloader using JForex Java SDK over JPype."""

    @property
    def source_name(self) -> str:
        return "dukascopy"

    def list_available(self, **kwargs) -> list[dict]:
        del kwargs
        return [
            {
                "symbol": symbol,
                "instrument": config["instrument"],
                "asset_class": config["asset_class"],
                "timeframe": "tick,1m,5m,15m,30m,1h,4h,1d,1w",
            }
            for symbol, config in SYMBOL_CONFIG.items()
        ]

    def download(
        self,
        symbol: str,
        timeframe: str,
        output_dir: Path,
        *,
        start: str | None = None,
        end: str | None = None,
        **kwargs,
    ) -> DownloadResult:
        target_tf = _normalize_timeframe(timeframe)
        base_tf = BASE_TIMEFRAME_MAP[target_tf]

        offer_side = _normalize_offer_side(kwargs.get("offer_side", kwargs.get("price_type", "bid")))
        if offer_side == "both" and target_tf == "tick":
            raise ValueError("offer_side='both' is not supported for timeframe 'tick' with JForex")

        timeout_seconds = int(kwargs.get("query_timeout_seconds", 900))
        if timeout_seconds <= 0:
            raise ValueError("query_timeout_seconds must be > 0")

        cache_dir = kwargs.get("cache_dir")
        cache_path = (
            Path(cache_dir).expanduser().resolve() if cache_dir else (DATA_DIR / ".jforex-cache")
        )

        try:
            normalized_symbol, asset_class, java_instrument = _resolve_java_instrument(symbol)
        except _java_exception_types() as exc:
            _raise_jforex_runtime_error("JForex instrument resolution failed", exc)
        except Exception as exc:  # noqa: BLE001
            _raise_jforex_runtime_error("JForex instrument resolution failed", exc)
        out_path = self._make_output_path(output_dir, asset_class, normalized_symbol, target_tf)

        effective_start = self._resolve_resume_start(out_path, start) or "2003-01-01"
        effective_end = end or datetime.now(timezone.utc).date().isoformat()

        start_dt = _parse_datetime(effective_start, is_end=False)
        end_dt = _parse_datetime(effective_end, is_end=True)
        if end_dt <= start_dt:
            raise ValueError("end date/time must be after start date/time")

        auth = _read_auth_config()

        if offer_side == "both":
            if base_tf == "tick":
                raise ValueError(
                    "offer_side='both' is not supported for tick-derived outputs with JForex"
                )
            bid_out_path = _build_offer_side_output_path(out_path, target_tf, "bid")
            ask_out_path = _build_offer_side_output_path(out_path, target_tf, "ask")
            bid_df = _query_bars_for_offer_side(
                java_instrument=java_instrument,
                base_tf=base_tf,
                offer_side="bid",
                start_dt=start_dt,
                end_dt=end_dt,
                auth=auth,
                timeout_seconds=timeout_seconds,
                cache_path=cache_path,
            )
            ask_df = _query_bars_for_offer_side(
                java_instrument=java_instrument,
                base_tf=base_tf,
                offer_side="ask",
                start_dt=start_dt,
                end_dt=end_dt,
                auth=auth,
                timeout_seconds=timeout_seconds,
                cache_path=cache_path,
            )

            if bid_df.empty or ask_df.empty:
                raise RuntimeError(
                    f"No {base_tf} bid/ask data returned for {normalized_symbol} in range "
                    f"{effective_start} → {effective_end}"
                )

            if target_tf == base_tf:
                bid_result_df = bid_df
                ask_result_df = ask_df
            else:
                bid_result_df = _resample_offer_prefixed(bid_df, target_tf, "bid")
                ask_result_df = _resample_offer_prefixed(ask_df, target_tf, "ask")

            merged_bid = self._merge_and_store_single_file(bid_out_path, bid_result_df)
            merged_ask = self._merge_and_store_single_file(ask_out_path, ask_result_df)
            result_df = bid_result_df.merge(ask_result_df, on="timestamp", how="inner")
            result_df = (
                result_df.sort_values("timestamp")
                .drop_duplicates(subset=["timestamp"])
                .reset_index(drop=True)
            )
        else:
            base_df = _query_jforex_history(
                java_instrument=java_instrument,
                base_timeframe=base_tf,
                start_ms=int(start_dt.timestamp() * 1000),
                end_ms=int(end_dt.timestamp() * 1000),
                auth=auth,
                offer_side_name=offer_side.upper(),
                timeout_seconds=timeout_seconds,
                cache_dir=cache_path,
            )

            if base_df.empty:
                raise RuntimeError(
                    f"No {base_tf} data returned for {normalized_symbol} in range "
                    f"{effective_start} → {effective_end}"
                )

            if target_tf == "tick":
                result_df = base_df
            elif base_tf == target_tf:
                result_df = base_df
            else:
                result_df = resample_ohlcv(base_df, target_tf)

        if result_df.empty:
            raise RuntimeError(f"No data left after processing timeframe {target_tf}")

        if offer_side == "both":
            combined = result_df
            size_bytes = 0
            if bid_out_path.exists():
                size_bytes += bid_out_path.stat().st_size
            if ask_out_path.exists():
                size_bytes += ask_out_path.stat().st_size
            output_path = out_path.parent
        else:
            combined = self._merge_and_store_single_file(out_path, result_df)
            size_bytes = out_path.stat().st_size
            output_path = out_path
        warnings: list[str] = [f"offer_side:{offer_side}", f"price_type:{offer_side}"]
        if target_tf != base_tf:
            warnings.append(f"resampled_from:{base_tf}")
        if offer_side == "both":
            warnings.extend([f"stored_bid:{bid_out_path.name}", f"stored_ask:{ask_out_path.name}"])

        return DownloadResult(
            symbol=normalized_symbol,
            timeframe=target_tf,
            source=self.source_name,
            asset_class=asset_class,
            path=output_path,
            rows=len(combined),
            start=str(combined["timestamp"].iloc[0]) if len(combined) > 0 else "",
            end=str(combined["timestamp"].iloc[-1]) if len(combined) > 0 else "",
            size_bytes=size_bytes,
            warnings=warnings,
        )

    def get_source_meta(self) -> SourceMeta:
        return SourceMeta(
            name=self.source_name,
            url="https://www.dukascopy.com",
            license="account_required",
            update_frequency="manual",
            downloaded_at=datetime.now(timezone.utc).isoformat(),
        )


def download(
    symbol: str,
    start_date: str,
    end_date: str,
    timeframe: str,
    *,
    output_dir: Path | None = None,
    **kwargs,
) -> DownloadResult:
    """Convenience function for direct module-level downloads."""
    downloader = JForexDownloader()
    return downloader.download(
        symbol=symbol,
        timeframe=timeframe,
        output_dir=output_dir or DATA_DIR,
        start=start_date,
        end=end_date,
        **kwargs,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Download Dukascopy data via JForex SDK (JPype)")
    parser.add_argument("--symbols", help="Comma-separated symbols (e.g. EURUSD,GBPUSD)")
    parser.add_argument(
        "--timeframes",
        default="1h",
        help="Comma-separated timeframes (tick,1m,5m,15m,30m,1h,4h,1d,1w)",
    )
    parser.add_argument("--start", required=True, help="Start date (YYYY-MM-DD or ISO timestamp)")
    parser.add_argument("--end", required=True, help="End date (YYYY-MM-DD or ISO timestamp)")
    parser.add_argument("--output", default=str(DATA_DIR), help="Output root directory")
    parser.add_argument(
        "--offer-side",
        "--price-type",
        dest="offer_side",
        choices=["bid", "ask", "both"],
        default="bid",
    )
    parser.add_argument("--query-timeout-seconds", type=int, default=900)
    parser.add_argument("--list", action="store_true", help="List known symbols")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)s  %(message)s")
    downloader = JForexDownloader()

    if args.list:
        for item in downloader.list_available():
            print(f"{item['symbol']:20s} {item['instrument']:20s} {item['asset_class']}")
        return

    if not args.symbols:
        parser.error("--symbols is required (or use --list)")

    output_dir = Path(args.output)
    symbols = [part.strip() for part in args.symbols.split(",") if part.strip()]
    timeframes = [part.strip() for part in args.timeframes.split(",") if part.strip()]

    completed = 0
    for symbol in symbols:
        for timeframe in timeframes:
            try:
                result = downloader.download(
                    symbol=symbol,
                    timeframe=timeframe,
                    output_dir=output_dir,
                    start=args.start,
                    end=args.end,
                    offer_side=args.offer_side,
                    query_timeout_seconds=args.query_timeout_seconds,
                )
                completed += 1
                print(
                    f"✅ {result.symbol} {result.timeframe}: {result.rows} rows "
                    f"({result.start} → {result.end}) → {result.path}"
                )
            except Exception as exc:  # noqa: BLE001
                print(f"❌ {symbol} {timeframe}: {exc}")

    print(f"\nDone: {completed} downloads completed.")


if __name__ == "__main__":
    main()
