"""
JForex Downloader — Dukascopy historical data via JForex Java SDK (JPype bridge).

This downloader connects to Dukascopy through the JForex SDK, requests historical
bars/ticks, and stores data under the canonical OHLCV path:

    {output_dir}/ohlcv/dukascopy/{asset_class}/{symbol}/{timeframe}.parquet

Supported output timeframes:
    tick, 1m, 5m, 15m, 30m, 1h, 4h, 1d, 1w

Native JForex periods:
    tick, 1m, 1h, 1d

Non-native output timeframes are automatically generated by downloading the nearest
native base timeframe and resampling via data_tools.resample.resample_ohlcv.
"""

