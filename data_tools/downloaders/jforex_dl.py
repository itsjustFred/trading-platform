def _is_allowed_dukascopy_url(url: str) -> bool:
    """Return True only for Dukascopy-hosted remote resources (DV-B6a)."""
    try:
        parsed = urlparse(str(url or "").strip())
    except ValueError:
        return False
    if parsed.scheme not in {"https", "http"}:
        return False
    host = (parsed.hostname or "").lower()
    if not host:
        return False
    return any(
        host == suffix.lstrip(".") or host.endswith(suffix)
        for suffix in DUKASCOPY_ALLOWED_HOST_SUFFIXES
    )


def _require_allowed_dukascopy_url(url: str, context: str) -> None:
    if not _is_allowed_dukascopy_url(url):
        raise RuntimeError(
            f"Refusing to fetch {context} from non-Dukascopy host: {url!r}. "
            "The JForex downloader only accepts JNLP/JAR resources from "
            "Dukascopy hosts."
        )


def _load_expected_jar_digests() -> dict[str, str]:
    """Parse the optional JAR digest pin list from the environment."""
    raw = (os.getenv(EXPECTED_JAR_DIGEST_ENV) or "").strip()
    if not raw:
        return {}
    digests: dict[str, str] = {}
    for entry in raw.split(","):
        entry = entry.strip()
        if not entry or "=" not in entry:
            continue
        url, _, digest = entry.partition("=")
        url = url.strip()
        digest = digest.strip().lower()
        if url and digest:
            digests[url] = digest
    return digests


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _verify_jar_digest(path: Path, url: str, expected_digests: dict[str, str]) -> bool:
    """Verify a downloaded JAR against a pinned digest (DV-B6b).

    Returns True when there is nothing pinned for ``url`` (no expectation to
    check) or when the digest matches. A mismatch is a hard failure: the
    artifact is deleted and a RuntimeError raised so it can never reach the
    JVM classpath.
    """
    expected = (expected_digests or {}).get(url)
    if not expected:
        return True
    actual = _sha256_file(path)
    if actual.lower() == expected.lower():
        return True
    try:
        path.unlink()
    except OSError:  # pragma: no cover - best-effort quarantine
        pass
    raise RuntimeError(
        f"Integrity check failed for downloaded JAR '{url}': "
        f"expected sha256 {expected}, got {actual}. The file was removed and "
        "will not be added to the classpath."
    )


def _discover_jars(root: Path) -> list[Path]:
    if not root.exists():
        return []

    search_roots = [root]
    if (root / "lib").exists():
        search_roots.append(root / "lib")
    if (root / "libs").exists():
        search_roots.append(root / "libs")

    jars: list[Path] = []
    for search_root in search_roots:
        jars.extend(sorted(path for path in search_root.rglob("*.jar") if path.is_file()))

    deduped: list[Path] = []
    seen: set[Path] = set()
    for jar in jars:
        if jar in seen:
            continue
        deduped.append(jar)
        seen.add(jar)
    return deduped


def _resolve_existing_path(path: Path) -> Path | None:
    try:
        candidate = path.expanduser()
        if not candidate.exists():
            return None
        return candidate.resolve(strict=True)
    except OSError:
        return None


def _parse_jnlp_jar_urls(jnlp_url: str, *, _visited: set[str] | None = None) -> list[str]:
    visited = _visited if _visited is not None else set()
    if jnlp_url in visited:
        return []
    visited.add(jnlp_url)

    _require_allowed_dukascopy_url(jnlp_url, "JNLP descriptor")

    try:
        with urlopen(jnlp_url, timeout=20) as response:
            payload = response.read()
    except URLError as exc:
        raise RuntimeError(f"Failed to fetch JNLP '{jnlp_url}': {exc}") from exc

    try:
        root = ET.fromstring(payload)
    except ET.ParseError as exc:
        raise RuntimeError(f"Invalid JNLP payload from '{jnlp_url}': {exc}") from exc

    codebase = (root.attrib.get("codebase") or "").strip()
    base_url = codebase or jnlp_url
    jar_urls: list[str] = []

    for element in root.iter():
        tag = element.tag.rsplit("}", 1)[-1].lower()
        href = (element.attrib.get("href") or "").strip()
        if not href:
            continue
        if tag in {"jar", "nativelib"}:
            jar_urls.append(urljoin(base_url, href))
        elif tag == "extension":
            extension_url = urljoin(base_url, href)
            _require_allowed_dukascopy_url(extension_url, "JNLP extension")
            jar_urls.extend(_parse_jnlp_jar_urls(extension_url, _visited=visited))

    deduped: list[str] = []
    seen: set[str] = set()
    for entry in jar_urls:
        if entry in seen:
            continue
        deduped.append(entry)
        seen.add(entry)
    return deduped


def _download_jforex_jars_from_jnlp(
    jnlp_url: str,
    target_dir: Path,
    jar_urls: list[str] | None = None,
) -> list[Path]:
    _require_allowed_dukascopy_url(jnlp_url, "JNLP descriptor")

    resolved_urls = _parse_jnlp_jar_urls(jnlp_url) if jar_urls is None else list(jar_urls)
    for jar_url in resolved_urls:
        _require_allowed_dukascopy_url(jar_url, "JAR resource")
    if not resolved_urls:
        raise RuntimeError(f"No jar resources found in JNLP '{jnlp_url}'.")

    expected_digests = _load_expected_jar_digests()
    target_dir.mkdir(parents=True, exist_ok=True)
    downloaded: list[Path] = []

    for jar_url in resolved_urls:
        file_name = Path(urlparse(jar_url).path).name
        if not file_name.endswith(".jar"):
            continue
        output_path = target_dir / file_name
        if not output_path.exists() or output_path.stat().st_size == 0:
            try:
                with urlopen(jar_url, timeout=30) as response:
                    output_path.write_bytes(response.read())
            except URLError as exc:
                raise RuntimeError(f"Failed to download JAR '{jar_url}': {exc}") from exc
        _verify_jar_digest(output_path, jar_url, expected_digests)
        downloaded.append(output_path)

    if not downloaded:
        raise RuntimeError(f"JNLP '{jnlp_url}' did not resolve any downloadable JAR files.")

    deduped: list[Path] = []
    seen: set[Path] = set()
    for path in downloaded:
        if path in seen:
            continue
        deduped.append(path)
        seen.add(path)
    return deduped


def _resolve_jforex_classpath() -> list[str]:
    classpath, _ = _resolve_jforex_classpath_details()
    return classpath


def _resolve_jforex_classpath_details() -> tuple[list[str], str]:
    explicit = os.getenv("JFOREX_CLASSPATH") or os.getenv("JFOREX_JARS")
    if explicit:
        return [entry.strip() for entry in explicit.split(os.pathsep) if entry.strip()], "explicit env"

    repo_root = Path(__file__).resolve().parents[2]
    home_env = os.getenv("JFOREX_HOME")
    candidates: list[Path] = []
    if home_env:
        candidates.append(Path(home_env).expanduser())
    candidates.extend(
        [
            DATA_DIR / ".jforex-sdk",
            repo_root / "download" / "jforex",
            repo_root / "download" / "jforex-sdk",
            repo_root / "download",
        ]
    )

    classpath: list[str] = []
    for root in candidates:
        classpath.extend(str(path.resolve(strict=True)) for path in _discover_jars(root))

    if classpath:
        return classpath, "local discovery"

    bootstrap_dir = DATA_DIR / ".jforex-sdk"
    jnlp_url = _resolve_jnlp_url()
    # DV-B7: bootstrap failures are surfaced, not swallowed into an empty
    # classpath (which later degraded into an opaque "Could not resolve
    # classpath" error far away from the root cause).
    downloaded = _download_jforex_jars_from_jnlp(jnlp_url, bootstrap_dir)
    logger.info("Bootstrapped %d JForex SDK jars from %s", len(downloaded), jnlp_url)
    return [str(path.resolve(strict=True)) for path in downloaded], f"jnlp bootstrap: {jnlp_url}"


def _trusted_java_home_roots() -> list[Path]:
    configured = (
        os.getenv("JFOREX_TRUSTED_JAVA_HOMES")
        or os.getenv("JFOREX_TRUSTED_JAVA_HOME")
        or ""
    ).strip()
    if configured:
        roots: list[Path] = []
        for entry in configured.split(os.pathsep):
            candidate = entry.strip()
            if candidate:
                roots.append(Path(candidate).expanduser())
        if roots:
            return roots

    return [
        Path(r"C:\Program Files\Java"),
        Path(r"C:\Program Files\Eclipse Adoptium"),
        Path(r"C:\Program Files\Microsoft"),
        Path("/Library/Java/JavaVirtualMachines"),
        Path("/usr/lib/jvm"),
        Path("/usr/java"),
        Path("/opt/java"),
    ]

def _jvm_candidates_from_java_home(java_home: str | None) -> list[str]:
    if not java_home:
        return []

    root = Path(java_home).expanduser().resolve(strict=False)
    candidates = [
        root / "bin" / "server" / "jvm.dll",  # Windows JDK/JRE
        root / "jre" / "bin" / "server" / "jvm.dll",  # Legacy Windows layouts
        root / "lib" / "server" / "libjvm.so",  # Linux JDK/JRE
        root / "jre" / "lib" / "server" / "libjvm.so",  # Legacy Linux layouts
        root / "lib" / "server" / "libjvm.dylib",  # macOS JDK/JRE
        root / "jre" / "lib" / "server" / "libjvm.dylib",  # Legacy macOS layouts
    ]
    resolved_candidates: list[str] = []
    seen: set[str] = set()
    for candidate in candidates:
        resolved = _resolve_existing_path(candidate)
        if resolved is None:
            continue
        key = os.path.normcase(str(resolved))
        if key in seen:
            continue
        seen.add(key)
        resolved_candidates.append(str(resolved))
    return resolved_candidates


def _is_trusted_java_home(java_home: Path) -> bool:
    resolved_home = _resolve_existing_path(java_home)
    if resolved_home is None:
        return False

    for root in _trusted_java_home_roots():
        resolved_root = _resolve_existing_path(root)
        if resolved_root is None:
            continue
        if resolved_home == resolved_root or resolved_root in resolved_home.parents:
            return True
    return False


def _is_trusted_custom_jvm_path(jvm_path: Path) -> bool:
    resolved_path = _resolve_existing_path(jvm_path)
    if resolved_path is None:
        return False
    file_name = resolved_path.name.lower()
    if file_name not in {"jvm.dll", "libjvm.so", "libjvm.dylib"}:
        return False

    parents = resolved_path.parents
    java_home_candidates: list[Path] = []
    if len(parents) >= 3 and parents[0].name == "server":
        java_home_candidates.append(parents[2])
    if len(parents) >= 4 and parents[0].name == "server" and parents[2].name == "jre":
        java_home_candidates.append(parents[3])

    return any(_is_trusted_java_home(candidate) for candidate in java_home_candidates)


def _discover_jvm_paths() -> list[str]:
    candidates: list[str] = []

    # Explicit override is only honored when opted in and resolves to a trusted location.
    explicit = (os.getenv("JFOREX_JVM_PATH") or "").strip()
    if explicit:
        path = _resolve_existing_path(Path(explicit))
        if path is not None and os.getenv("JFOREX_ALLOW_CUSTOM_JVM") == "1":
            if _is_trusted_custom_jvm_path(path):
                candidates.append(str(path))

    java_homes: list[str] = []
    env_java_home = (os.getenv("JAVA_HOME") or "").strip()
    if env_java_home:
        java_homes.append(env_java_home)

    if os.name == "nt":
        java_homes.extend(
            [
                r"C:\Program Files\Java\jdk-17",
                r"C:\Program Files\Java\jdk-21",
                r"C:\Program Files\Java\jdk-17.0.1",
            ]
        )
    else:
        java_homes.extend(
            [
                "/usr/lib/jvm/default-java",
                "/usr/lib/jvm/java-17-openjdk-amd64",
                "/usr/lib/jvm/java-21-openjdk-amd64",
            ]
        )

    for home in java_homes:
        java_home_path = Path(home)
        if not _is_trusted_java_home(java_home_path):
            continue
        for jvm_path in _jvm_candidates_from_java_home(home):
            candidates.append(jvm_path)

    # Let JPype try its own platform-specific discovery as a fallback.
    try:
        default_jvm = _jpype_module().getDefaultJVMPath() if JPYPE_AVAILABLE else ""
    except Exception:  # noqa: BLE001
        default_jvm = ""
    if default_jvm:
        resolved_default = _resolve_existing_path(Path(default_jvm))
        if resolved_default is not None:
            candidates.append(str(resolved_default))

    # Preserve order but remove duplicates.
    deduped: list[str] = []
    seen: set[str] = set()
    for entry in candidates:
        resolved_entry = _resolve_existing_path(Path(entry))
        if resolved_entry is None:
            continue
        norm = os.path.normcase(str(resolved_entry))
        if norm in seen:
            continue
        seen.add(norm)
        deduped.append(str(resolved_entry))
    return deduped


def _format_jvm_startup_diagnostics(
    *,
    classpath: list[str],
    classpath_source: str,
    candidates: list[tuple[str, str]],
    final_error: BaseException,
) -> str:
    lines = [
        "Failed to start JVM for JForex SDK.",
        f"Classpath source: {classpath_source}",
        f"Classpath entries ({len(classpath)}):",
    ]
    for entry in classpath:
        lines.append(f"  - {entry}")

    lines.append(f"JVM candidates tried ({len(candidates)}):")
    if candidates:
        for candidate, reason in candidates:
            lines.append(f"  - {candidate}")
            lines.append(f"    reason: {reason}")
    else:
        lines.append("  - none")

    lines.append(f"Last error: {final_error}")
    return "\n".join(lines)


def _ensure_jvm_started() -> None:
    jpype_mod = _jpype_module()

    with JVM_START_LOCK:
        if not jpype_mod.isJVMStarted():
            classpath, classpath_source = _resolve_jforex_classpath_details()
            if not classpath:
                raise RuntimeError(
                    "Could not resolve JForex SDK classpath. "
                    "Set JFOREX_CLASSPATH (or JFOREX_JARS) to your SDK jars."
                )

            jvm_candidates = _discover_jvm_paths()
            startup_errors: list[tuple[str, str]] = []

            for jvm_path in jvm_candidates:
                try:
                    jpype_mod.startJVM(jvm_path, classpath=classpath, convertStrings=False)
                    break
                except Exception as exc:  # noqa: BLE001
                    # DV-B5: a failing candidate is recorded and the next one is
                    # tried — including Java-originated exceptions, which
                    # previously aborted the loop on the first candidate.
                    logger.debug("JVM candidate failed: %s", jvm_path, exc_info=True)
                    startup_errors.append((jvm_path, str(exc)))

            if not jpype_mod.isJVMStarted():
                # Final attempt uses JPype default startup in case candidates were incomplete.
                try:
                    jpype_mod.startJVM(classpath=classpath, convertStrings=False)
                except _java_exception_types() as exc:
                    _raise_jforex_runtime_error("Failed to start JVM for JForex SDK", exc)
                except Exception as exc:  # noqa: BLE001
                    diagnostics = _format_jvm_startup_diagnostics(
                        classpath=classpath,
                        classpath_source=classpath_source,
                        candidates=startup_errors,
                        final_error=exc,
                    )
                    raise RuntimeError(diagnostics) from exc

    _ensure_jvm_thread_context_class_loader()


def _ensure_jvm_thread_context_class_loader() -> None:
    if not JPYPE_AVAILABLE:
        return

    jpype_mod = jpype
    if not jpype_mod.isJVMStarted():
        return

    try:
        java_thread = jpype_mod.JClass("java.lang.Thread")
        class_loader = jpype_mod.JClass("java.lang.ClassLoader")

        current_thread = java_thread.currentThread()
        if current_thread.getContextClassLoader() is not None:
            return

        loader = class_loader.getSystemClassLoader()
        if loader is None:
            from com.dukascopy.api.system import ClientFactory

            loader = ClientFactory.class_.getClassLoader()
        if loader is None:
            raise RuntimeError("No Java class loader available for JForex SDK thread context.")

        current_thread.setContextClassLoader(loader)
        logger.debug("Initialized Java thread context class loader for JForex SDK access")
    except _java_exception_types() as exc:
        _raise_jforex_runtime_error(
            "Failed to initialize JVM thread context class loader",
            exc,
        )
    except Exception as exc:  # noqa: BLE001
        raise RuntimeError(
            f"Failed to initialize JVM thread context class loader: {exc}"
        ) from exc


