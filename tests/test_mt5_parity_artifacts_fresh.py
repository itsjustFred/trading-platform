"""Guard: the committed MT5-parity artifacts must match the current strategy code.

The artifacts under data/backtests/ are regenerated by hand (a multi-GB data run), so
nothing else notices when a later change to the strategy defaults leaves them stale.
This cheap check fails on parameter drift and on internally inconsistent stats,
without re-running the data pipeline.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from strategies.intraday_volatility_breakout.intraday_volatility_breakout import (
    STRATEGY_META,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = [
    REPO_ROOT / "data" / "backtests" / f"intraday_volatility_breakout_{case}.json"
    for case in ("eurusd_h1", "nas100_m15", "sp500_m1")
]
# Semantics this PR introduced; the artifacts must have been produced with the defaults.
SEMANTIC_DEFAULTS = ("atr_smoothing", "daily_weekend_bars", "daily_skip_filler_bars")


@pytest.mark.parametrize("path", ARTIFACTS, ids=lambda p: p.stem)
def test_parity_artifact_matches_current_strategy_defaults(path: Path) -> None:
    if not path.exists():
        pytest.skip(f"{path.name} not present in this checkout")
    data = json.loads(path.read_text(encoding="utf-8"))
    params = data["meta"]["parameters"]
    defaults = STRATEGY_META["parameters"]
    for key in SEMANTIC_DEFAULTS:
        assert params.get(key) == defaults[key], (
            f"{path.name}: {key}={params.get(key)!r} but the strategy default is "
            f"{defaults[key]!r}; regenerate with scripts/regenerate_mt5_parity_artifacts.py"
        )
    assert params.get("broker_clock"), f"{path.name}: produced without a broker clock"


@pytest.mark.parametrize("path", ARTIFACTS, ids=lambda p: p.stem)
def test_parity_artifact_stats_agree_with_its_trades(path: Path) -> None:
    if not path.exists():
        pytest.skip(f"{path.name} not present in this checkout")
    data = json.loads(path.read_text(encoding="utf-8"))
    trades, stats = data["trades"], data["stats"]
    assert stats["total_trades"] == len(trades)
    total = sum(float(t.get("net_pnl", t["pnl"])) for t in trades)
    assert stats["total_pnl"] == pytest.approx(total, abs=0.01 * max(1, len(trades)))
